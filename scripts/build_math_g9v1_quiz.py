_CN_MAP = {"一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6,
           "七": 7, "八": 8, "九": 9}


def _cn_to_int(s):
    if s == "十":
        return 10
    if s.startswith("十"):
        return 10 + _CN_MAP[s[1]]
    if s.endswith("十"):
        return _CN_MAP[s[0]] * 10
    if "十" in s:
        a, b = s.split("十")
        return _CN_MAP[a] * 10 + _CN_MAP[b]
    return _CN_MAP[s]


