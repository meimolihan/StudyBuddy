def verify(units):
    """按题干反解数字重新算一遍，与标注答案比对。"""
    import re
    total = good = bad = skipped = 0
    bads = []
    for unit, lessons in units:
        for lesson, _b, qs in lessons:
            for t, stem, opts, ans in qs:
                total += 1
                exp = expect_g1(stem)
                if exp is None:
                    skipped += 1
                    continue
                if Decimal(str(exp)) == Decimal(str(opts[0])) if _isnum(exp) else str(exp) == opts[0]:
                    good += 1
                else:
                    bad += 1
                    bads.append((lesson, stem, exp, opts[0]))
    print("自动验算：共 %d 题，验算 %d 题（正确 %d / 错误 %d），未覆盖 %d 题"
          % (total, good + bad, good, bad, skipped))
    for lesson, stem, exp, got in bads[:20]:
        print("   ✗ %s | %s → 期望 %s，实际 %s" % (lesson, stem[:60], exp, got))
    return 1 if bad else 0


def _isnum(x):
    try:
        Decimal(str(x))
        return True
    except Exception:  # noqa: BLE001
        return False


