_CN_MAP = {"一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6,
           "七": 7, "八": 8, "九": 9}


def _cn_to_int(s):
    if s == "十":
        return 10
    if s.startswith("十"):
        return 10 + _CN_MAP[s[1]]
    if s.endswith("十"):
        return _CN_MAP[s[0]] * 10
    if "十" in s:
        a, b = s.split("十")
        return _CN_MAP[a] * 10 + _CN_MAP[b]
    return _CN_MAP[s]


def _unit_dir_cn_fix(unit, index):
    m = _re.match(r"^第([一二三四五六七八九十]+)章\s*", unit)
    if m:
        name = unit[m.end():].strip()
        return _ql.safe("%02d-%s" % (_cn_to_int(m.group(1)), name))
    return _ql.safe("%02d-%s" % (index, unit.strip()))


_ql.unit_dir = _unit_dir_cn_fix


