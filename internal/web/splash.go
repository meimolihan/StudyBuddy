// RandomSplashVerse 随机取一句开屏诗句（math/rand 全局源并发安全）。
// 末句句末标点在此统一去除：开屏上下句错位展示，末句不带符号。
func RandomSplashVerse() SplashVerse {
	v := splashVerses[rand.Intn(len(splashVerses))]
	v.L2 = strings.TrimRight(v.L2, "。，！？、；,.!?; ")
	return v
}

// SplitVerseLine 把一句诗按逗号拆成上下两句；无逗号时下句为空。
// 供构建诗句池时手工维护使用，保留以防后续批量导入。
func SplitVerseLine(s string) (string, string) {
	if i := strings.IndexAny(s, "，,"); i >= 0 {
		return s[:i], s[i+1:]
	}
	return s, ""
}
